CREATE TABLE IF NOT EXISTS "treatment_invoices" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "invoice_number" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "resident_number" integer NOT NULL REFERENCES "راس العلاج"("رقم النزيل") ON DELETE RESTRICT,
  "resident_id" uuid REFERENCES "residents"("id") ON DELETE SET NULL,
  "resident_name" text DEFAULT '' NOT NULL,
  "invoice_date" date NOT NULL,
  "notes" text DEFAULT '' NOT NULL,
  "prescription_pathname" text,
  "prescription_content_type" text,
  "total" double precision DEFAULT 0 NOT NULL,
  "voided" boolean DEFAULT false NOT NULL,
  "void_reason" text DEFAULT '' NOT NULL,
  "voided_at" timestamp with time zone,
  "voided_by" text REFERENCES "user"("id") ON DELETE RESTRICT,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "created_by" text REFERENCES "user"("id") ON DELETE SET NULL,
  CONSTRAINT "treatment_invoices_total_check" CHECK ("total" >= 0),
  CONSTRAINT "treatment_invoices_void_audit_check" CHECK (("voided" = false AND "voided_at" IS NULL AND "voided_by" IS NULL) OR ("voided" = true AND "voided_at" IS NOT NULL AND "voided_by" IS NOT NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS "treatment_invoices_number_unique"
  ON "treatment_invoices" ("invoice_number");
CREATE INDEX IF NOT EXISTS "treatment_invoices_resident_number_idx"
