  ON "treatment_invoices" ("invoice_date");
CREATE INDEX IF NOT EXISTS "treatment_invoices_voided_by_idx"
  ON "treatment_invoices" ("voided_by");
CREATE INDEX IF NOT EXISTS "treatment_invoices_created_by_idx"
  ON "treatment_invoices" ("created_by");

