function convert(raw, col) {
  const s = raw === undefined || raw === null ? "" : String(raw);
  if (s.trim() === "") {
    if (col.is_nullable === "YES") return null;
    return TEXTUAL.has(col.data_type) ? "" : null;
  }
  if (col.data_type === "boolean") {
    const k = s.trim().toLowerCase();
    if (TRUE_SET.has(k)) return true;
    if (FALSE_SET.has(k)) return false;
    throw new Error(`قيمة boolean غير مفهومة في العمود ${col.column_name}`);
  }
  if (["smallint", "integer", "bigint"].includes(col.data_type)) {
    if (!/^[+-]?\d+$/u.test(s.trim())) {
      const error = new Error("INVALID_INTEGER");
      error.code = "INVALID_VALUE";
      throw error;
    }
    return s.trim();
  }
  if (col.data_type === "date" || col.data_type.startsWith("timestamp")) {
    const datePattern = /^(\d{4})-(\d{1,2})-(\d{1,2})(?:[ T](\d{1,2}):(\d{2})(?::(\d{2})(?:\.(\d+))?)?(?:\s*(AM|PM))?)?$/iu;
    const slashPattern = /^(\d{1,2})\/(\d{1,2})\/(\d{4})(?:[ T](\d{1,2}):(\d{2})(?::(\d{2})(?:\.(\d+))?)?(?:\s*(AM|PM))?)?$/iu;
    let parts = s.trim().match(datePattern);
    let year;
    let month;
    let day;
    let time;
    if (parts) {
      [, year, month, day] = parts;
      time = parts[4] ? parts.slice(4, 9) : null;
    } else {
      parts = s.trim().match(slashPattern);
      if (!parts) {
        const error = new Error("UNSUPPORTED_DATE_FORMAT");
        error.code = "INVALID_VALUE";
        throw error;
      }
      let first = Number(parts[1]);
      let second = Number(parts[2]);
      year = parts[3];
      if (first <= 12 && second <= 12 && first !== second) {
        if (!sourceDateOrder) {
          const error = new Error("AMBIGUOUS_DATE_FORMAT");
          error.code = "INVALID_VALUE";
          throw error;
        }
        if (sourceDateOrder === "day-first") [first, second] = [second, first];
      }
      if (first > 12) [first, second] = [second, first];
      month = first;
      day = second;
      time = parts[4] ? parts.slice(4, 9) : null;
    }
    year = Number(year);
    month = Number(month);
    day = Number(day);
    const calendar = new Date(Date.UTC(year, month - 1, day));
    if (
      calendar.getUTCFullYear() !== year ||
      calendar.getUTCMonth() !== month - 1 ||
      calendar.getUTCDate() !== day
    ) {
      const error = new Error("INVALID_DATE");
      error.code = "INVALID_VALUE";
      throw error;
    }
    const date = `${String(year).padStart(4, "0")}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
    if (col.data_type === "date") return date;
    let [hour, minute, second = "0", fraction = "", meridian = ""] = time ?? [];
    if (!hour) return date;
    hour = Number(hour);
    if (meridian) {
      if (hour < 1 || hour > 12) {
        const error = new Error("INVALID_TIME");
        error.code = "INVALID_VALUE";
        throw error;
      }
      hour = (hour % 12) + (meridian.toUpperCase() === "PM" ? 12 : 0);
    }
    const clock = [hour, Number(minute), Number(second)];
    if (clock[0] > 23 || clock[1] > 59 || clock[2] > 59) {
      const error = new Error("INVALID_TIME");
      error.code = "INVALID_VALUE";
      throw error;
    }
    const fractional = fraction ? `.${fraction}` : "";
    return `${date} ${clock.map((value) => String(value).padStart(2, "0")).join(":")}${fractional}`;
  }
  return TEXTUAL.has(col.data_type) ? s : s.trim();
}
function dateShape(raw) {
  const value = String(raw ?? "").trim();
  if (!value) return "blank";
  if (/^\d{4}-\d{1,2}-\d{1,2}(?:[ T].*)?$/u.test(value)) return "iso-date-or-timestamp";
  const slashDate = value.match(/^(\d{1,2})[/-](\d{1,2})[/-](\d{2,4})(?:[ T].*)?$/u);
  if (slashDate) {
    const first = Number(slashDate[1]);
    const second = Number(slashDate[2]);
    const order = slashDate[3].length === 2
      ? "two-digit-year"
      : first > 12
        ? "day-first"
        : second > 12
          ? "month-first"
          : first === second
            ? "equal-components"
            : "ambiguous-order";
    const clock = /(?:AM|PM)/iu.test(value)
      ? "12-hour"
      : /[ T]\d{1,2}:\d{2}/u.test(value)
        ? "24-hour"
        : "date-only";
    return `slash-${order}-${clock}`;
  }
  if (/^\d+(?:\.\d+)?$/u.test(value)) return "numeric-serial";
  if (/(?:AM|PM)/iu.test(value)) return "twelve-hour-clock";
  return value.replace(/[A-Za-z\u0600-\u06FF]+/gu, "X").replace(/\d/gu, "#");
}

function readCsv(file) {
  try {
    const text = new TextDecoder(ENCODING)
      .decode(fs.readFileSync(file))
      .replace(/^\uFEFF/, "");
    return parse(text, {
      columns: true,
      skip_empty_lines: true,
      relax_column_count: false,
    });
  } catch {
    throw new Error(`CSV_PARSE_FAILED=${path.basename(file)}`);
  }
}

