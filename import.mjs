const sourceId = (row, index) => {
  const key = Object.keys(row).find((name) => ["id", "id1"].includes(norm(name)));
  const value = key ? String(row[key] ?? "").trim() : "";
  return value || `row:${index + 2}`;
};
const sourcePayload = (row) =>
  Object.fromEntries(Object.entries(row).filter(([key]) => !key.startsWith("__")));
const isRowDataError = (error) =>
  error?.code === "INVALID_VALUE" ||
  /^(22|23)/.test(error?.code ?? "");
async function quarantineRow(table, id, row, reason) {
  await client.query(
    `INSERT INTO public.import_quarantine
       (source_table, source_id, payload, reason, status)
     VALUES ($1, $2, $3::jsonb, $4, 'pending')
     ON CONFLICT (source_table, source_id) DO UPDATE
       SET payload = EXCLUDED.payload, reason = EXCLUDED.reason,
           status = 'pending', resolved_at = NULL, resolved_by = NULL`,
    [table, id, JSON.stringify(sourcePayload(row)), reason],
  );
}
async function quarantineRowsBatch(table, entries) {
  const latestById = new Map();
  for (const entry of entries) latestById.set(entry.id, entry);
  const uniqueEntries = [...latestById.values()];
  for (let offset = 0; offset < uniqueEntries.length; offset += 200) {
    const batch = uniqueEntries.slice(offset, offset + 200);
    const values = [];
    const tuples = batch.map(({ id, row, reason }, index) => {
      const base = index * 4;
      values.push(table, id, JSON.stringify(sourcePayload(row)), reason);
      return `($${base + 1}, $${base + 2}, $${base + 3}::jsonb, $${base + 4}, 'pending')`;
    });
    await client.query(
      `INSERT INTO public.import_quarantine
         (source_table, source_id, payload, reason, status)
       VALUES ${tuples.join(",")}
       ON CONFLICT (source_table, source_id) DO UPDATE SET
         payload = EXCLUDED.payload, reason = EXCLUDED.reason,
         status = 'pending', resolved_at = NULL, resolved_by = NULL`,
      values,
    );
  }
}
