async function connectWithRetry() {
  for (let attempt = 0; attempt <= maxRetries; attempt += 1) {
    const client = new pg.Client({
      connectionString: url,
      connectionTimeoutMillis,
    });
    try {
      await client.connect();
      return client;
    } catch (error) {
      await client.end().catch(() => {});
      if (!isTimeoutError(error) || attempt === maxRetries) {
        throw new Error(`DATABASE_CONNECTION_FAILED=${errorCode(error)}`);
      }
      console.warn(`DATABASE_TIMEOUT_RETRY=${attempt + 1}/${maxRetries}`);
      await new Promise((resolve) => setTimeout(resolve, (attempt + 1) * 1000));
    }
  }
  throw new Error("DATABASE_CONNECTION_FAILED=DB_ERROR");
}

